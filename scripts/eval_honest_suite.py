def load_model(ckpt_path: Path, device: str) -> tuple[Parentheses, Tokenizer]:
    tok_dir = REPO_ROOT / "data" / "tokenizer" / "v3_32k"
    tok = Tokenizer.from_file(str(tok_dir / "tokenizer.json"))
    tok.encode_special_tokens = True

    print(f"Loading checkpoint from {ckpt_path} on {device}...")
    ckpt = torch.load(ckpt_path, map_location=device, weights_only=False)
    cfg = ckpt.get("cfg") or ckpt.get("config")
    if not isinstance(cfg, ModelConfig):
        cfg_dict = cfg if isinstance(cfg, dict) else {}
        cfg = ModelConfig(
            vocab_size=cfg_dict.get("vocab_size", 32768),
            block_size=cfg_dict.get("block_size", 4096),
            n_layer=cfg_dict.get("n_layer", 32),
            n_head=cfg_dict.get("n_head", 8),
            n_embd=cfg_dict.get("n_embd", 512),
            attn_type=cfg_dict.get("attn_type", "selective_linear"),
        )
    model = Parentheses(cfg)
    sd = ckpt["model"] if "model" in ckpt else ckpt
    clean_sd = {k.replace("_orig_mod.", ""): v for k, v in sd.items()}
    model.load_state_dict(clean_sd, strict=True)
    model.to(device).eval()
    return model, tok


def run_eval(model: Parentheses, tok: Tokenizer, device: str, max_new_tokens: int = 192):
    tag_map = {
        "eng": tok.token_to_id("<eng>"),
        "kan": tok.token_to_id("<kan>"),
        "tam": tok.token_to_id("<tam>"),
        "tel": tok.token_to_id("<tel>"),
        "mal": tok.token_to_id("<mal>"),
    }
    user_id = tok.token_to_id("<|user|>")
    asst_id = tok.token_to_id("<|assistant|>")
    think_id = tok.token_to_id("<think>")
    think_end_id = tok.token_to_id("</think>")
    eot_id = tok.token_to_id("<|endoftext|>")
    stops = {eot_id, tok.token_to_id("<|user|>"), tok.token_to_id("<|system|>")} - {None}

    results = []
    print("\n" + "=" * 70)
    print("PARENT-0.9 HONEST EVALUATION SUITE (RAW GREEDY - ZERO CHEATS)")
    print("=" * 70)

    for tc in TEST_CASES:
        t_id = tc["id"]
        cat = tc["cat"]
        lang = tc["lang"]
        prompt = tc["prompt"]
        expected = tc["expected"]

        l_tag = tag_map.get(lang, tag_map["eng"])
        p_ids = tok.encode(prompt, add_special_tokens=False).ids
        in_ids = [user_id, l_tag] + p_ids + [asst_id]
        idx = torch.tensor([in_ids], dtype=torch.long, device=device)

        # Pure greedy generation (temperature=0 or very low, top_k=1)
        out_tokens = []
        with torch.no_grad():
            for nxt in model.stream(idx, max_new_tokens=max_new_tokens, temperature=1e-5, top_k=1):
                t = int(nxt.item())
                if t in stops:
                    break
                out_tokens.append(t)

        full_output = tok.decode(out_tokens, skip_special_tokens=False)
        # Parse think vs answer
        if "</think>" in full_output:
            raw_think, ans_part = full_output.split("</think>", 1)
            think_part = raw_think.replace("<think>", "").strip()
        else:
            think_part, ans_part = "", full_output

        clean_ans = ans_part.strip()
        ans_check = clean_ans
        if "=" in clean_ans:
            ans_check = clean_ans.split("=")[-1]
        ans_lower = ans_check.lower()
        passed = any(exp.lower() in ans_lower for exp in expected)

        status_str = f"{STYLE_PASS}PASS{STYLE_RESET}" if passed else f"{STYLE_FAIL}FAIL{STYLE_RESET}"
        print(f"\n[{t_id}] ({cat}) {prompt}")
        if think_part.strip():
            print(f"{STYLE_THINK}[think] {think_part.strip()[:180]}...{STYLE_RESET}")
        print(f"{STYLE_ANSWER}[answer] {clean_ans}{STYLE_RESET} -> {status_str}")

        results.append({
            "id": t_id,
            "cat": cat,
            "lang": lang,
            "prompt": prompt,
            "passed": passed,
            "output": clean_ans,
            "think": think_part.strip(),
            "expected": expected,
        })

    # Summary
    print("\n" + "=" * 70)
    print("EVALUATION SUMMARY")
    print("=" * 70)
    total = len(results)
    passed_cnt = sum(1 for r in results if r["passed"])
    print(f"Overall Accuracy: {passed_cnt}/{total} ({passed_cnt/total*100:.1f}%)")
    
    cats = {}
    for r in results:
        c = r["cat"]
        cats.setdefault(c, []).append(r["passed"])
    for c, p_list in cats.items():
        print(f"  - {c:25s}: {sum(p_list)}/{len(p_list)} ({sum(p_list)/len(p_list)*100:.1f}%)")

    return results


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--checkpoint", type=str, required=True)
    parser.add_argument("--device", type=str, default="cuda" if torch.cuda.is_available() else "cpu")
    parser.add_argument("--out-json", type=str, default=None)
    args = parser.parse_args()

    model, tok = load_model(Path(args.checkpoint), args.device)
    results = run_eval(model, tok, args.device)

    if args.out_json:
        p = Path(args.out_json)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(json.dumps(results, indent=2, ensure_ascii=False), encoding="utf-8")
        print(f"Saved evaluation report to {p}")


if __name__ == "__main__":
    main()
